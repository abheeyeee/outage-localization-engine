import React, { useState } from 'react';
import { X, Sparkles, Copy, Check, ShieldAlert, MapPin } from 'lucide-react';

export default function BriefingModal({ briefing, onClose }) {
  const [copied, setCopied] = useState(false);

  if (!briefing) return null;

  const handleCopy = () => {
    const text = `
=== ${briefing.title} ===
Severity: ${briefing.severity}
Target Node: ${briefing.target_id}
Location: ${briefing.location}

${briefing.topology_note}

ACTION PLAN:
${briefing.action_plan.join('\n')}

SAFETY PROTOCOL:
${briefing.safety_warning}

Generated by: ${briefing.generated_by}
    `.trim();

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div style={{
      position: 'fixed',
      top: 0,
      left: 0,
      width: '100vw',
      height: '100vh',
      backgroundColor: 'rgba(0, 0, 0, 0.75)',
      backdropFilter: 'blur(8px)',
      zIndex: 2000,
      display: 'flex',
      alignItems: 'center',
      justifyContent: 'center'
    }}>
      <div className="glass-panel" style={{
        width: '580px',
        maxHeight: '85vh',
        overflowY: 'auto',
        padding: '24px',
        display: 'flex',
        flexDirection: 'column',
        gap: '16px',
        boxShadow: '0 20px 50px rgba(0, 0, 0, 0.6)'
      }}>
        {/* Modal Header */}
        <div style={{ display: 'flex', alignItems: 'flex-start', justifyContent: 'space-between' }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: '10px' }}>
            <div style={{
              width: '32px',
              height: '32px',
              borderRadius: '8px',
              background: 'linear-gradient(135deg, #38bdf8 0%, #3b82f6 100%)',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center'
            }}>
              <Sparkles size={18} color="#ffffff" />
            </div>
            <div>
              <h3 style={{ fontSize: '1rem', fontWeight: 700, color: '#f1f5f9' }}>AI Crew Dispatch Briefing</h3>
              <p style={{ fontSize: '0.75rem', color: '#94a3b8' }}>Generated for Field Lineman Crew</p>
            </div>
          </div>
          <button 
            onClick={onClose}
            style={{ background: 'none', border: 'none', color: '#64748b', cursor: 'pointer', padding: '4px' }}
          >
            <X size={20} />
          </button>
        </div>

        {/* Title & Severity */}
        <div style={{ background: 'rgba(15, 23, 42, 0.8)', padding: '14px', borderRadius: '8px', border: '1px solid var(--border-color)' }}>
          <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '6px' }}>
            <span className="badge badge-red">{briefing.severity} SEVERITY</span>
            <span style={{ fontSize: '0.8rem', color: '#94a3b8', display: 'flex', alignItems: 'center', gap: '4px' }}>
              <MapPin size={14} color="#38bdf8" />
              {briefing.location}
            </span>
          </div>
          <h4 style={{ fontSize: '0.95rem', fontWeight: 600, color: '#f1f5f9' }}>{briefing.title}</h4>
        </div>

        {/* Topology Note (MST Imputed Warning) */}
        <div style={{
          background: briefing.is_imputed ? 'rgba(249, 115, 22, 0.15)' : 'rgba(34, 197, 94, 0.15)',
          border: briefing.is_imputed ? '1px solid rgba(249, 115, 22, 0.3)' : '1px solid rgba(34, 197, 94, 0.3)',
          borderRadius: '8px',
          padding: '12px',
          fontSize: '0.85rem',
          color: briefing.is_imputed ? '#f97316' : '#22c55e',
          lineHeight: '1.4'
        }}>
          {briefing.topology_note}
        </div>

        {/* Action Plan */}
        <div>
          <h4 style={{ fontSize: '0.85rem', fontWeight: 600, color: '#94a3b8', uppercase: 'true', marginBottom: '8px' }}>
            FIELD ACTION PLAN:
          </h4>
          <ul style={{ listStyle: 'none', display: 'flex', flexDirection: 'column', gap: '6px', fontSize: '0.85rem' }}>
            {briefing.action_plan.map((step, i) => (
              <li key={i} style={{ background: 'rgba(255, 255, 255, 0.03)', padding: '8px 12px', borderRadius: '6px', borderLeft: '3px solid #38bdf8' }}>
                {step}
              </li>
            ))}
          </ul>
        </div>

        {/* Safety Protocol */}
        <div style={{
          background: 'rgba(239, 68, 68, 0.15)',
          border: '1px solid rgba(239, 68, 68, 0.3)',
          borderRadius: '8px',
          padding: '12px',
          display: 'flex',
          alignItems: 'flex-start',
          gap: '10px'
        }}>
          <ShieldAlert size={20} color="#ef4444" style={{ flexShrink: 0, marginTop: '2px' }} />
          <div style={{ fontSize: '0.8rem', color: '#fca5a5', lineHeight: '1.4' }}>
            <strong>SAFETY WARNING:</strong> {briefing.safety_warning}
          </div>
        </div>

        {/* Footer Actions */}
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', paddingTop: '8px', borderTop: '1px solid var(--border-color)' }}>
          <span style={{ fontSize: '0.75rem', color: '#64748b' }}>{briefing.generated_by}</span>
          <button
            onClick={handleCopy}
            style={{
              background: copied ? 'rgba(34, 197, 94, 0.2)' : 'linear-gradient(135deg, #38bdf8 0%, #3b82f6 100%)',
              border: 'none',
              color: '#ffffff',
              borderRadius: '6px',
              padding: '8px 16px',
              fontSize: '0.8rem',
              fontWeight: 600,
              cursor: 'pointer',
              display: 'flex',
              alignItems: 'center',
              gap: '6px'
            }}
          >
            {copied ? <Check size={14} /> : <Copy size={14} />}
            {copied ? 'Copied to Clipboard!' : 'Copy Dispatch Briefing'}
          </button>
        </div>
      </div>
    </div>
  );
}
